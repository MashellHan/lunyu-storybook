import asyncio, os, time, json, sys
from playwright.async_api import async_playwright
D=os.path.dirname(os.path.abspath(__file__)); U="file://"+os.path.abspath(os.path.join(D,"..","index-v6.html")); O=os.path.join(D,"..","v6shots")
os.makedirs(O,exist_ok=True)
async def main():
  async with async_playwright() as p:
    b=await p.chromium.launch(executable_path="/usr/bin/google-chrome",args=["--autoplay-policy=user-gesture-required"])
    ctx=await b.new_context(viewport={"width":1180,"height":820},record_video_dir=os.path.join(O,"vid"),record_video_size={"width":1180,"height":820})
    pg=await ctx.new_page(); t0=time.time()*1000
    errs=[]; pg.on("pageerror",lambda e:errs.append(str(e))); pg.on("console",lambda m: m.type=="error" and errs.append(m.text))
    await pg.goto(U)
    await pg.wait_for_timeout(2600); await pg.screenshot(path=f"{O}/v6-01-title.png")
    st=await pg.evaluate("document.querySelector('#book').dataset.step"); print("after intro step:",st)
    await pg.click("#startBtn")
    await pg.wait_for_function("document.querySelector('#book').dataset.step==='title-voice'",timeout=5000)
    await pg.wait_for_timeout(2300); await pg.screenshot(path=f"{O}/v6-02-title-voice-karaoke.png")
    await pg.wait_for_function("document.querySelector('#book').dataset.step==='trumpet'",timeout=15000)
    await pg.wait_for_timeout(500); await pg.screenshot(path=f"{O}/v6-02b-elephant-trumpet.png")
    await pg.wait_for_function("document.querySelector('#book').dataset.step==='e1'",timeout=15000)
    await pg.wait_for_timeout(2100); await pg.screenshot(path=f"{O}/v6-03-elephant-karaoke-midline.png")
    await pg.wait_for_function("document.querySelector('#book').dataset.step==='u1'",timeout=15000)
    await pg.wait_for_timeout(1900); await pg.screenshot(path=f"{O}/v6-04-unison-echo.png")
    await pg.wait_for_function("document.querySelector('#book').dataset.step==='e2'",timeout=15000)
    await pg.wait_for_timeout(1500)
    log=await pg.evaluate("window.__log"); json.dump({"t0":t0,"log":log},open(f"{O}/vid-log.json","w"))
    await pg.wait_for_function("document.querySelector('#book').dataset.step==='again'",timeout=60000)
    await pg.wait_for_timeout(900); await pg.screenshot(path=f"{O}/v6-05-again.png")
    await pg.wait_for_function("document.querySelector('#book').dataset.step==='solo-bunny'",timeout=15000)
    await pg.wait_for_timeout(500); await pg.screenshot(path=f"{O}/v6-06-bunny-hop.png")
    await pg.wait_for_timeout(1900); await pg.screenshot(path=f"{O}/v6-07-bunny-solo-karaoke.png")
    await pg.wait_for_function("document.querySelector('#book').dataset.step==='sound-bunny'",timeout=15000)
    await pg.wait_for_timeout(300); await pg.screenshot(path=f"{O}/v6-08-bunny-squeak.png")
    await pg.wait_for_function("document.querySelector('#book').dataset.step==='solo-cat'",timeout=15000)
    await pg.wait_for_timeout(2600); await pg.screenshot(path=f"{O}/v6-09-cat-solo.png")
    await pg.wait_for_function("document.querySelector('#book').dataset.step==='solo-dog'",timeout=20000)
    await pg.wait_for_timeout(560); await pg.screenshot(path=f"{O}/v6-10-dog-flip.png")
    await pg.wait_for_timeout(2000); await pg.screenshot(path=f"{O}/v6-11-dog-solo-karaoke.png")
    await pg.wait_for_function("document.querySelector('#book').dataset.step==='sound-dog'",timeout=15000)
    await pg.wait_for_timeout(500); await pg.screenshot(path=f"{O}/v6-12-dog-woof.png")
    await pg.wait_for_function("document.querySelector('#book').dataset.step==='free'",timeout=20000)
    await pg.wait_for_timeout(1300); await pg.screenshot(path=f"{O}/v6-13-freeplay-taprings.png")
    await pg.click("#cat"); await pg.wait_for_timeout(2400); await pg.screenshot(path=f"{O}/v6-14-free-tap-cat.png")
    await pg.click("#elephant"); await pg.wait_for_timeout(500); await pg.screenshot(path=f"{O}/v6-15-free-tap-elephant-trumpet.png")
    await pg.wait_for_timeout(2300)
    await pg.click("#pauseBtn"); await pg.wait_for_timeout(1500)
    ct1=await pg.evaluate("__demo.audio.currentTime"); await pg.wait_for_timeout(1000); ct2=await pg.evaluate("__demo.audio.currentTime")
    print("paused audio frozen:",ct1==ct2, ct1, ct2); await pg.screenshot(path=f"{O}/v6-16-paused.png")
    print("errors:",errs)
    await ctx.close(); await b.close()
asyncio.run(main())
